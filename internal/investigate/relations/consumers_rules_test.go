// rulesFixtures are the environments of the golden graphs.
func rulesFixtures(t *testing.T) map[string]*fixture {
	plain := newFixture(t)
	plain.file("apps/billing/all.yaml", consumerEnv)
	gen := genFixture(t)
	gen.overlay("kustomize:apps/api/overlays/eu", genRender)
	pod := newFixture(t)
	pod.file("apps/ledger/all.yaml", podSpecEnv)
	return map[string]*fixture{"plain": plain, "generated": gen, "pod-spec": pod}
}

// Rules v1 and v2 rebuild their graphs byte for byte: transcripts recorded
// under them replay only against the graphs they saw. The golden graphs were
// written by the code before rules v3 (ledger D-0006) and are never
// regenerated by a later rules version.
func TestConsumerRulesGolden(t *testing.T) {
	for name, f := range rulesFixtures(t) {
		for _, rules := range []int{ConsumerRulesV1, ConsumerRulesV2} {
			for _, side := range []Side{SideTo, SideFrom} {
				g, err := BuildConsumerGraph(context.Background(), f.st, f.b, side, WithConsumerRules(rules))
				if err != nil {
					t.Fatal(err)
				}
				got, err := json.MarshalIndent(g, "", "  ")
				if err != nil {
					t.Fatal(err)
				}
				got = append(got, '\n')
				file := filepath.Join("testdata", "consumer-rules", fmt.Sprintf("%s-%s-v%d.json", name, side, rules))
				if *updateRules {
					if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
						t.Fatal(err)
					}
					if err := os.WriteFile(file, got, 0o644); err != nil {
						t.Fatal(err)
					}
					continue
				}
				want, err := os.ReadFile(file)
				if err != nil {
					t.Fatal(err)
				}
				if !bytes.Equal(got, want) {
					t.Errorf("%s: the rules-v%d graph differs from its golden graph", file, rules)
				}
			}
		}
	}
}
