#!/usr/bin/env python3
"""Write the evidence-equivalence table of one case (PROTOCOL §3).

    evidence-md.py <case-dir> <arm-B run dir> <workspace> > EVIDENCE.md

Reads the arm-B bundle.json and request.json from the stored run's
cases.tar.gz (manifest and evidence records only: no findings, claims or
transcripts), the case's input.yaml and env/, the materialised evidence
($P6_EVIDENCE/<case-id>/artifacts.tsv) and the built workspace.
"""
import hashlib, io, json, os, re, subprocess, sys, tarfile, tempfile
import yaml

case_dir, run_dir, ws = (os.path.abspath(a) for a in sys.argv[1:4])
here = os.path.dirname(os.path.abspath(__file__))
inp = yaml.safe_load(open(os.path.join(case_dir, "input.yaml")))
cid, product = inp["id"], inp["product"]
env_root = os.path.join(case_dir, inp["environment"].get("root", "env/").rstrip("/"))
evdir = os.path.join(os.environ.get("P6_EVIDENCE", os.path.expanduser("~/ri-p6/evidence")), cid)
run_id = os.path.basename(run_dir)

with tarfile.open(os.path.join(run_dir, "cases.tar.gz")) as t:
    bundle = json.load(t.extractfile(f"cases/{cid}/bundle.json"))
    request = json.load(t.extractfile(f"cases/{cid}/request.json"))
arts = bundle["manifest"]["artifacts"]
sha = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()
short = lambda h: h[:16] + "…"
mat = {}
for line in open(os.path.join(evdir, "artifacts.tsv")).read().splitlines()[1:]:
    path, h, kind, origin, uri, src = line.split("\t")
    mat[path] = (h, src)
nonart = {}
for line in open(os.path.join(here, "env-nonartifact.tsv")):
    if line.startswith("#") or not line.strip(): continue
    c, p, d, why = line.rstrip("\n").split("\t")
    if c == cid: nonart[p] = (d, why)
renders = [l.split("\t") for l in open(os.path.join(evdir, "renders.tsv")).read().splitlines()]
mode = os.environ.get("P6_ENV", "readback")

# Every marker line of the env files and renders RI stored, with what RI's
# read tools read back (scripts/phase6/readback: RI's own code).
paths = sorted({p for p in mat if p.startswith("env/")} | {f for r in renders for f in r[2:] if f})
with tempfile.TemporaryDirectory() as tmp:
    subprocess.run(["go", "run", "./scripts/phase6/readback", "-evidence", evdir, "-out", os.path.join(tmp, "out"),
                    "-tsv", os.path.join(tmp, "m.tsv"), "-authored", env_root] + paths,
                   cwd=os.path.dirname(os.path.dirname(here)), check=True)
    markers = [l.split("\t") for l in open(os.path.join(tmp, "m.tsv")).read().splitlines()[1:]]

out = []
w = out.append
w(f"# Evidence equivalence — `{cid}`\n")
w(f"Generated by `scripts/phase6/evidence-md.py` (lane ws6) for the commander's review (ledger X-0002). "
  f"Arm-B run `{run_id}`, bundle `{bundle['id']}`. Workspace built by `scripts/phase6/build-workspace.sh` "
  f"(env mode `{mode}`), `MANIFEST.sha256` digest `{sha(os.path.join(ws, 'MANIFEST.sha256'))}`. "
  f"Every RI-side byte below was re-materialised by `scripts/phase6/materialise.sh` (deterministic `ri investigate`, "
  f"no agent, offline, scratch state) and checked against the digest the arm-B bundle records; "
  f"bytes found only in the arm-B run's own CAS are marked.\n")
w("RI's agent reached raw sources through `read_artifact`, `search_manifest` and `get_rendered_object` (every "
  "manifest artifact), and saw verbatim upstream excerpts through `get_change_item`/`get_dossier` (evidence "
  "records). Its other tools return RI-derived outputs, which PROTOCOL §3 excludes.\n")

# 1. Raw artifacts
w("## 1. Raw sources RI's agent could read as artifacts\n")
w("| source (RI bundle path) | kind | in workspace | workspace path | sha256 |")
w("|---|---|---|---|---|")
for a in sorted(arts, key=lambda a: a["path"]):
    if a["origin"] == "derived" and not (a["kind"] == "rendered-manifests" and a["path"].startswith("derived/render/env/")):
        continue
    p, h = a["path"], a["digest"].split(":", 1)[1]
    note = "" if mat.get(p, (None, ""))[1] != "extra-cas" else " (bytes from the arm-B run's CAS; a fresh fetch differs)"
    if a["origin"] == "environment":
        rel = p[len("env/"):]
        wp = "env/" + rel
        got = sha(os.path.join(ws, wp))
        redacted = sha(os.path.join(env_root, rel)) != h
        state = ("yes, RI's bytes" if got == h else "yes, RI's bytes + read-back comments" if mode == "readback"
                 else "yes, as authored (P6_ENV=raw)") + (" — RI redacted values, §6" if redacted else "")
        w(f"| `{p}` | {a['kind']} | {state} | `{wp}` | `{short(h)}` |")
    elif a["origin"] == "upstream":
        wp = "upstream/" + p[len(f"upstream/{product}/"):]
        same = sha(os.path.join(ws, wp)) == h
        w(f"| `{a['uri']}` | {a['kind']} | {'yes' if same else '**MISMATCH**'}{note} | `{wp}` | `{short(h)}` |")
    else:
        tgt = next((r for r in renders if p in r[2:]), None)
        w(f"| `{p}` | environment render ({tgt[0] if tgt else '?'}, {tgt[1] if tgt else '?'}) | yes, inside `rendered/*.yaml` (§2) | `rendered/` | `{short(h)}` |")
w("")

# 2. Composite workspace files
w("## 2. Workspace files built from those sources\n")
w("| workspace path | built from | sha256 |\n|---|---|---|")
for f, how in [("rendered/from.yaml", "the FROM side of every environment render target above, in RI's order, each under a `# =====` header naming the target; a target RI found version-independent (not-applicable, FROM only) appears identically in both files" + ("; read-back comments as in §6" if mode == "readback" else "")),
               ("rendered/to.yaml", "the TO side, likewise"),
               ("rendered/manifest.diff", "`diff -u` of the two (replaces RI's semantic render diff, which is derived)"),
               ("ORIENTATION.md", "input.yaml: product, chart, from/to version and chart version, Kubernetes version, `environment.description` verbatim; no case id, no scope")]:
    w(f"| `{f}` | {how} | `{short(sha(os.path.join(ws, f)))}` |")
w("")

# 3. Environment files RI did not ingest
w("## 3. Files under the case's env/ that RI did not ingest\n")
ingested = {a["path"][4:] for a in arts if a["origin"] == "environment"}
rows = []
for root, _, files in os.walk(env_root):
    for fn in files:
        rel = os.path.relpath(os.path.join(root, fn), env_root)
        if rel not in ingested:
            d, why = nonart.get(rel, ("**undecided**", ""))
            rows.append(f"| `env/{rel}` | {d} | {why} |")
w("| file | in workspace | why |\n|---|---|---|")
w("\n".join(sorted(rows)) if rows else "| (none) | | |")
w("")

# 4. Evidence excerpts without a backing artifact
w("## 4. Upstream excerpts RI's agent saw without the full source (evidence records)\n")
backed = {a.get("uri") for a in arts}
backed |= {re.sub(r"^https://raw\.githubusercontent\.com/([^/]+/[^/]+)/", r"https://github.com/\1/blob/", u or "") for u in backed}
loose, longest = {}, 0
for e in bundle.get("evidence", []):
    u = e.get("uri") or ""
    if not u.startswith("http") or u in backed: continue
    longest = max(longest, len(e.get("excerpt") or ""))
    loose.setdefault((e.get("kind"), re.sub(r"sha256:[0-9a-f]+", "sha256:…", u)), 0)
    loose[(e.get("kind"), re.sub(r"sha256:[0-9a-f]+", "sha256:…", u))] += 1
w("RI shows these as short verbatim excerpts in change items and dossiers; no full source behind them was in its "
  f"bundle, and the workspace has no file for them. The longest such excerpt is {longest} characters: registry and "
  "release metadata (image digests, chart index entries, tag dates) and the first line of release assets or static "
  "manifests, whose substance is in the renders (image references) and in `ORIENTATION.md` (versions).\n")
w("| kind | URI | records |\n|---|---|---|")
for (k, u), n in sorted(loose.items()):
    w(f"| {k} | `{u}` | {n} |")
w("")

# 5. Excluded derived outputs
w("## 5. RI outputs left out (derived; PROTOCOL §3)\n")
kinds = {}
for a in arts:
    if a["origin"] == "derived" and not (a["kind"] == "rendered-manifests" and a["path"].startswith("derived/render/env/")):
        key = a["kind"] + (" (release scope: chart defaults)" if "/release/" in a["path"] else "")
        kinds[key] = kinds.get(key, 0) + 1
w("| bundle artifact kind | count |\n|---|---|")
for k, n in sorted(kinds.items()): w(f"| {k} | {n} |")
w("\nAlso outside the bundle manifest and not in the workspace: change items, findings, classes, the relationship "
  "graph and impact paths (`expand_graph`, `list_paths`), dossiers, validations (`request_validation`), claims and "
  "assertions, knowledge facts, and the agent's transcript.\n")

# 6. Known differences
w("## 6. Known differences between the two arms' evidence\n")
n = 1
# Workspace line of each stored line: env files keep their lines; renders sit
# under the k-th "# =====" header of rendered/<side>.yaml, in renders.tsv order.
rows = []
for p, line, path, marker, value, note, authored in markers:
    i = int(line)
    stored = open(os.path.join(evdir, "files", p)).read().splitlines()[i - 1].strip()
    rb = f'`"{value}"`' if value else "not read back"
    if p.startswith("env/"):
        src = open(os.path.join(env_root, p[4:])).read().splitlines()[i - 1].strip()
        rows.append((p, i, path, f"`{src}`", f"`{stored}`", rb))
        continue
    for side in ("from", "to"):
        k, hl = -1, 0
        for j, l in enumerate(open(os.path.join(ws, f"rendered/{side}.yaml")).read().splitlines(), 1):
            if l.startswith("# ===== "):
                k += 1
                r = renders[k]
                if (r[3] if side == "to" and r[3] else r[2]) == p: hl = j
        if hl:
            src = f'`"{authored}"` (value in env/)' if authored else "no env/ value has this digest (chart template output)"
            rows.append((f"rendered/{side}.yaml", hl + i, path, src, f"`{stored}`", rb))
if rows:
    back = sum(1 for r in rows if r[5] != "not read back")
    w(f"{n}. **RI's redaction markers and its read-back (decision D1, X-0002).** RI stores some env values as "
      "`<redacted sha256:…>` and its renders mask fields as `<sensitive sha256:…>`; RI's agent read those bytes "
      "verbatim. Its read tools (`read_artifact`, `get_rendered_object`, …) also return a `readBack` list: a "
      "withheld value that is a string enum value its CRD declares is read back from its digest "
      "(`redaction.Schemas.Recover`, `internal/investigate/agent/withheld.go`), with the note `stored redacted as "
      "<marker>: the digest of \"<value>\", an enum value its CRD declares for <path> (not a credential)`. "
      f"The workspace (env mode `{mode}`) " + {
        "readback": "keeps RI's bytes, markers verbatim, and appends RI's note, computed by RI's own code "
                    "(`scripts/phase6/readback`), as a YAML comment to each line whose marker RI reads back; a marker "
                    "RI does not read back stays masked with no comment.",
        "ri": "keeps RI's bytes only, without the read-back: less than RI's agent had.",
        "raw": "has the env files as authored (no markers there) and RI's renders as stored."}[mode] +
      f" {len(rows)} marker lines, {back} read back:\n")
    w("   | workspace file | line | field | as authored | as RI stored it | RI read-back |\n   |---|---|---|---|---|---|")
    for f, i, path, src, stored, rb in sorted(rows, key=lambda r: (not r[0].startswith("env/"), r[0], r[1])):
        w(f"   | `{f}` | {i} | `{path}` | {src} | {stored} | {rb} |")
    w("\n   **Remaining difference.** RI gives a read-back value as a separate structured field of the tool result "
      "(`readBack`: object, path, marker, value, note), next to the verbatim text and only when the window read "
      "holds the marker; the workspace gives it as an inline YAML comment on the marker's line, wherever the file "
      "is read (`kubectl kustomize` output drops comments, as it would any). The note's wording is RI's, "
      "including the marker.\n")
    n += 1
else:
    w(f"{n}. **RI's redaction markers and its read-back (decision D1, X-0002).** None: no env file or render RI "
      f"stored holds a `<redacted sha256:…>` or `<sensitive sha256:…>` marker, so env mode `{mode}` gives RI's bytes "
      "unchanged and nothing is read back.\n")
    n += 1
desc = bool(request.get("environment", {}).get("description"))
w(f"{n}. **Environment description.** `ORIENTATION.md` carries `environment.description` verbatim, as PROTOCOL §3 "
  f"prescribes. RI's agent request {'had' if desc else 'had **no**'} description (the arm-B `request.json` holds product, versions, "
  f"environment name, repository and Kubernetes version only), so the natural agent has this orientation text and "
  f"RI's agent did not.\n"); n += 1
w(f"{n}. **Release-scope (chart-default) renders.** RI's agent could read renders of each chart version with default "
  "values (`list_renders`, scope release). The workspace has only the environment's renders (PROTOCOL §3); the "
  "chart's own `values.yaml` for both versions is in `upstream/`.\n"); n += 1
w(f"{n}. **Diff form.** RI's agent queried a semantic per-object diff with change classes and correlations "
  "(`query_diff`, derived); the workspace has a plain `diff -u` of the concatenated renders.\n"); n += 1
w(f"{n}. **Tools and budgets.** RI's agent: 15 MCP tools over the bundle, 40 turns, 80 tool calls, 600k tokens, "
  "4 MiB of reads, 400 lines per read. Natural agent: Read/Grep/Glob, Bash limited to read-only commands "
  "(`ls cat head tail wc find grep diff jq yq`, `kubectl kustomize`; `yq` is not installed on this machine), "
  "writes only to `scratch/`, 400k tokens (counted as RI counts them), no turn cap. Neither has network access.\n"); n += 1
w(f"{n}. **Training knowledge.** Both arms use `claude-sonnet-5-5`, which may know these releases.\n")
print("\n".join(out))
